void* Cmm_FindLocalVar(const Cmm_Activation *a, unsigned n) {
  pc_map_entry* entry = a->rtdata;
  assert(entry);
  if (n >= entry->num_locals)
    die("local var index %d out of range", n);
  return locptr(a, locals(entry)[n]);
}
