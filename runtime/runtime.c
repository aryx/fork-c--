Cmm_Cont* Cmm_CreateThread(Cmm_Codeptr f, Cmm_Dataptr x, void *s, unsigned n) {
  char *stack = s;
  char *young, *old, *vfp;
  Cmm_Cont *k;
  if (Cmm_stack_growth < 0) {
    /*s: set up stack for growth downward */
    young = stack;
    old   = stack + n;
    k = (Cmm_Cont *) old;
    k--;
    k->sp = (Cmm_Word*) (vfp = old - sizeof(*k) - sizeof(f) - sizeof(x));
    k->pc = Cmm_start_thread_helper;
    *(Cmm_Codeptr*)vfp = f;
    vfp += sizeof(f);
    *(Cmm_Dataptr*)vfp = x;
    /*e: set up stack for growth downward */
    return k;
  } else {
    /*s: set up stack for growth upward */
    old   = stack;
    young = stack + n;
    k = (Cmm_Cont *) old;
    k++;
    k->sp = (Cmm_Word*) (vfp = old + sizeof(*k) + sizeof(f) + sizeof(x));
    k->pc = Cmm_start_thread_helper;
    *(Cmm_Codeptr*)vfp = f;
    vfp -= sizeof(f);
    *(Cmm_Dataptr*)vfp = x;
    /*e: set up stack for growth upward */
    return k;
  }
}
