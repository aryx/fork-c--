Cmm_Dataptr Cmm_GetDescriptor(const Cmm_Activation *a, Cmm_Word token) {
  unsigned num_spans;
  Cmm_Word* descs;
  pc_map_entry* entry = a->rtdata;
  if (!entry)
    return 0;

  num_spans = entry->num_spans;
  if ((unsigned) token < num_spans) {
    descs = spans(entry);
    return (Cmm_Dataptr)descs[token];
  } else {
    return 0;
  }
}
